import { pool } from "./pool.js";

/**
 * Mesmo esquema gerado pelo Hibernate (ddl-auto=update) a partir das entidades JPA.
 * `IF NOT EXISTS` garante que tanto faz qual backend sobe primeiro: as tabelas
 * criadas por um são reaproveitadas pelo outro.
 */
const DDL = `
CREATE TABLE IF NOT EXISTS cliente (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome            VARCHAR(120) NOT NULL,
  login           VARCHAR(120) NOT NULL UNIQUE,
  senha           VARCHAR(100) NOT NULL,
  cpf             VARCHAR(14),
  data_nascimento DATE,
  telefone        VARCHAR(20),
  estado_civil    VARCHAR(20),
  escolaridade    VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS servico_ti (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       VARCHAR(100)   NOT NULL,
  descricao  VARCHAR(500)   NOT NULL,
  preco      NUMERIC(12, 2) NOT NULL,
  prazo_dias INTEGER        NOT NULL
);

CREATE TABLE IF NOT EXISTS solicitacao_servico_ti (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id    BIGINT         NOT NULL REFERENCES cliente (id),
  servico_ti_id BIGINT         NOT NULL REFERENCES servico_ti (id),
  numero        VARCHAR(20)    NOT NULL,
  data_pedido   DATE           NOT NULL,
  status        VARCHAR(30)    NOT NULL,
  preco_cobrado NUMERIC(12, 2) NOT NULL,
  data_prevista DATE           NOT NULL
);
`;

// Catálogo da AV1 — idêntico ao CargaInicialServicos.java
const CATALOGO = [
  ["Manutenção de Servidores", "Manutenção preventiva e corretiva de servidores físicos e virtuais.", "1200.00", 3],
  ["Instalação de Redes", "Projeto e instalação de redes cabeadas e sem fio corporativas.", "2500.00", 7],
  ["Consultoria Cloud", "Planejamento e migração de ambientes locais para a nuvem.", "3800.00", 10],
  ["Backup Corporativo", "Implantação de rotinas de backup e recuperação de desastres.", "900.00", 2],
  ["Segurança da Informação", "Políticas de proteção de dados, firewall e antivírus corporativo.", "4200.00", 14]
];

export async function garantirEsquema() {
  await pool.query(DDL);
}

export async function cargaInicialServicos() {
  const { rows } = await pool.query("SELECT COUNT(*)::int AS total FROM servico_ti");
  if (rows[0].total > 0) return 0;

  for (const [nome, descricao, preco, prazo] of CATALOGO) {
    await pool.query(
      "INSERT INTO servico_ti (nome, descricao, preco, prazo_dias) VALUES ($1, $2, $3, $4)",
      [nome, descricao, preco, prazo]
    );
  }
  return CATALOGO.length;
}
